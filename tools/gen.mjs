// Output is committed: a KWin script has no build step and install.sh must run without Node.
//
//   node tools/gen.mjs            write the files
//   node tools/gen.mjs --check    exit non-zero if what is on disk differs

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(join(ROOT, p), "utf8");
const json = (p) => JSON.parse(read(p));

// QKeySequence reads xkb names like "Meta+Period" as no sequence, leaving the key dead.
const QT_KEY = { Escape: "Esc", Period: ".", Comma: ",", Minus: "-", Plus: "+", Equal: "=", Slash: "/",
  Backslash: "\\", Semicolon: ";", Apostrophe: "'", Grave: "`", BracketLeft: "[", BracketRight: "]" };
const qtChord = (chord) => {
  const parts = String(chord).split("+");
  return [...parts.slice(0, -1), QT_KEY[parts.at(-1)] ?? parts.at(-1)].join("+");
};

const kosmicKeys = () => {
  const km = json("keybindings.json");
  const own = km.bindings.filter((e) => e.owner === "kosmic");
  // ShortcutHandler holds one sequence, so an alias is a second name.
  const aliased = own.flatMap((e) => (e.aliases || []).map((c, i) =>
    ({ ...e, name: `${e.name}Alias${i + 1}`, chord: c, text: `${e.text} (alias)` })));
  return own.concat(aliased, km.additions).map((e) => ({ ...e, chord: qtChord(e.chord) }));
};

const kdeTargets = () => {
  const km = json("keybindings.json");
  const out = [];
  for (const e of km.bindings.filter((b) => b.owner === "kde")) {
    if (!e.native) throw new Error(`${e.action} is owned by KDE but names no native action`);
    for (const c of [e.chord, ...(e.aliases || [])]) {
      out.push({ component: e.native.component, action: e.native.action, chord: qtChord(c) });
    }
  }
  for (const e of km.system || []) {
    if (e.via) out.push({ component: e.via.component, action: e.via.action, chord: qtChord(e.chord) });
    else if (e.command) {
      out.push({ component: `kosmic-${e.command.id}.desktop`, action: "_launch", chord: qtChord(e.chord) });
    } else throw new Error(`system action ${e.action} has neither via nor command`);
  }
  return out;
};
const kdeCommands = () => (json("keybindings.json").system || []).filter((e) => e.command)
  .map((e) => ({ ...e.command, chord: qtChord(e.chord) }));

// Sorted so reordering keybindings.json does not renumber the plugin's chord indices.
const holdModes = () => {
  const km = json("keybindings.json");
  return Object.keys(km.modes || {}).sort()
    .map((name) => ({ name, hold: km.modes[name].hold }))
    .filter((m) => m.hold);
};

// QJSEngine cannot open files, so the keymap reaches the script as a module.
// Row: [name, text, sequence, modal, handler]; modal is null or the mode it binds under.
function keymap() {
  const km = json("keybindings.json");
  const keys = kosmicKeys();
  const rows = keys.map((e) =>
    `    [${JSON.stringify(e.name)}, ${JSON.stringify("KOSMIC: " + e.text)}, ` +
    `${JSON.stringify(e.chord)}, ${e.modal === undefined ? "null" : JSON.stringify(e.modal)}, ` +
    `${JSON.stringify(e.handler)}]`);

  // With chordHold on, kglobalaccel would match these toggles first and fire them alongside the gesture.
  const toggles = Object.values(km.modes || {})
    .filter((m) => m.hold).map((m) => m.hold.toggle);

  // ShortcutHandler needs a sequence to register; above the highest F-key in use so none collide.
  let fn = Math.max(12, ...keys.flatMap((e) =>
    [...String(e.chord).matchAll(/\bF(\d{1,2})\b/g)].map((m) => Number(m[1]))));
  const superseded = {};
  for (const e of keys) if (toggles.includes(e.handler)) superseded[e.name] = "Meta+F" + (++fn);

  return [
    "// Generated by tools/gen.mjs from keybindings.json. Do not edit.",
    "",
    "export const KEYS = [",
    rows.join(",\n"),
    "];",
    "",
    "// Registered with these instead of their own chord while chordHold is on: the plugin has to",
    "// see the key, so KWin cannot be holding a shortcut on it.",
    `export const SUPERSEDED = ${JSON.stringify(superseded, null, 4)};`,
    "",
  ].join("\n");
}

// evdev codes are layout-independent QWERTY positions. The modifier is absent on purpose: the
// plugin asks xkb, so any key the layout maps to Super works.
const SCANCODES = {
  Q: 16, W: 17, E: 18, R: 19, T: 20, Y: 21, U: 22, I: 23, O: 24, P: 25,
  A: 30, S: 31, D: 32, F: 33, G: 34, H: 35, J: 36, K: 37, L: 38,
  Z: 44, X: 45, C: 46, V: 47, B: 48, N: 49, M: 50,
};
const MODIFIERS = ["Meta", "Ctrl", "Alt", "Shift"];

function chordhold() {
  const keys = kosmicKeys();
  const lines = [];
  const modes = holdModes();

  modes.forEach(({ name, hold }, i) => {
    const toggle = keys.find((e) => (e.handler || "") === hold.toggle);
    if (!toggle) throw new Error(`mode "${name}" is held by handler "${hold.toggle}", which binds nothing`);

    const parts = String(toggle.chord).split("+");
    const mods = parts.filter((p) => MODIFIERS.includes(p));
    const rest = parts.filter((p) => !MODIFIERS.includes(p));
    if (mods.length !== 1 || rest.length !== 1) {
      throw new Error(`mode "${name}": "${toggle.chord}" is not one modifier plus one key`);
    }
    if (!(rest[0] in SCANCODES)) {
      throw new Error(`mode "${name}": no scan code known for "${rest[0]}" in "${toggle.chord}"`);
    }
    lines.push(
      `Modifier${i}=${mods[0]}`,
      `Key${i}=${SCANCODES[rest[0]]}`,
      `Arm${i}=${hold.arm}`,
      `Commit${i}=${hold.commit}`,
    );
  });

  return [
    "# Generated by tools/gen.mjs from keybindings.json. Do not edit.",
    "#",
    "# The chords kosmic-chordhold watches: each modifier by name, each key as an evdev scan code,",
    "# and the two shortcut names the plugin calls as the chord closes and opens. install.sh walks",
    "# this with kwriteconfig6. Without it the plugin loads, watches nothing, and the mode chords",
    "# are dead keys -- the script has already stood its own toggles down by then.",
    "",
    "[Plugin-kosmic-chordhold]",
    "Component=kwin",
    `Count=${modes.length}`,
    ...lines,
    "",
  ].join("\n");
}

// Needed where kglobalshortcutsrc already has entries, which win over QML defaults. A hold toggle
// left on its chord would fire alongside the gesture the plugin is holding.
function silenced() {
  const keys = kosmicKeys();
  const toggles = holdModes().map((m) => m.hold.toggle);
  const row = (when, e) => `${when}|kwin|${e.name}|KOSMIC: ${e.text}`;
  return [
    "# Generated by tools/gen.mjs from keybindings.json. Do not edit.",
    "#",
    "# <when>|<component>|<shortcut name>|<friendly name>, where <when> is `always` or",
    "# `chordhold`, the latter applying only where the plugin took the chord over. install.sh",
    "# writes each as `none,none,<friendly name>` into kglobalshortcutsrc.",
    "",
    ...keys.filter((e) => e.invokeOnly).map((e) => row("always", e)),
    ...keys.filter((e) => toggles.includes(e.handler || "")).map((e) => row("chordhold", e)),
    "",
  ].join("\n");
}

// Lets install.sh unbind a KDE default only if it still holds a chord KOSMIC takes.
function claimed() {
  const chords = [...new Set([...kosmicKeys(), ...kdeTargets()].map((e) => String(e.chord)))].sort();
  return [
    "# Generated by tools/gen.mjs from keybindings.json. Do not edit.",
    "#",
    "# Every chord KOSMIC takes, one per line: the ones it registers, and the ones it gives to a KDE",
    "# action. install.sh unbinds a colliding KDE default only where that default actually holds one",
    "# of these.",
    "",
    ...chords,
    "",
  ].join("\n");
}

// A stale `none` in kglobalshortcutsrc wins over the script's default; install.sh deletes those.
// Silenced names are excluded: `none` is what they should hold.
function own() {
  const toggles = holdModes().map((m) => m.hold.toggle);
  const rows = kosmicKeys()
    .filter((e) => !e.invokeOnly && e.modal === undefined && !toggles.includes(e.handler || ""))
    .map((e) => `${e.name}|${e.chord}`);
  return [
    "# Generated by tools/gen.mjs from keybindings.json. Do not edit.",
    "#",
    "# <shortcut name>|<chord it should hold>, for the names that always hold a chord.",
    "",
    ...[...new Set(rows)].sort(),
    "",
  ].join("\n");
}

function assign() {
  return [
    "# Generated by tools/gen.mjs from keybindings.json. Do not edit.",
    "#",
    "# <component>|<action>|<chord>: the chord is added to what the action already holds.",
    "",
    ...kdeTargets().map((t) => `${t.component}|${t.action}|${t.chord}`),
    "",
  ].join("\n");
}

function commands() {
  return [
    "# Generated by tools/gen.mjs from keybindings.json. Do not edit.",
    "#",
    "# <id>, <name>, <argument for install.d/kosmic-open>: each becomes kosmic-<id>.desktop, a command",
    "# shortcut, tab separated.",
    "",
    ...kdeCommands().map((c) => [c.id, c.name, c.arg].join("\t")),
    "",
  ].join("\n");
}

// Empty file and group: KWin supplies [Script-<id>] or [Effect-<id>] itself.
function kcfg(entries) {
  const lines = Object.entries(entries).map(([name, e]) => {
    const d = e.type === "Bool" ? String(e.default) : String(e.default);
    return `    <entry name="${name}" type="${e.type}">\n      <default>${d}</default>\n    </entry>`;
  });
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    "<!-- Generated by tools/gen.mjs from settings.json. Do not edit. -->",
    '<kcfg xmlns="http://www.kde.org/standards/kcfg/1.0"',
    '      xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"',
    '      xsi:schemaLocation="http://www.kde.org/standards/kcfg/1.0',
    '                          http://www.kde.org/standards/kcfg/1.0/kcfg.xsd">',
    '  <kcfgfile name=""/>',
    '  <group name="">',
    lines.join("\n"),
    "  </group>",
    "</kcfg>",
    "",
  ].join("\n");
}

const outputs = {
  "src/comp/script/contents/code/keymap.mjs": keymap(),
  "install.d/chordhold.ini": chordhold(),
  "install.d/silenced.txt": silenced(),
  "install.d/claimed.txt": claimed(),
  "install.d/own.txt": own(),
  "install.d/assign.txt": assign(),
  "install.d/commands.txt": commands(),
};
for (const c of Object.values(json("settings.json").components)) {
  if (c.kcfg) outputs[`${c.path}/contents/config/main.xml`] = kcfg(c.entries);
}

const version = read("VERSION").trim();
for (const path of ["src/applet/metadata.json", "src/comp/script/metadata.json",
                    "src/comp/effect/metadata.json", "src/comp/focusdim/metadata.json"]) {
  outputs[path] = read(path).replace(/("Version":\s*")[^"]*(")/, `$1${version}$2`);
}

const check = process.argv.includes("--check");
let stale = [];
for (const [path, want] of Object.entries(outputs)) {
  if (check) {
    let have = null;
    try { have = read(path); } catch { /* missing counts as stale */ }
    if (have !== want) stale.push(path);
  } else {
    mkdirSync(dirname(join(ROOT, path)), { recursive: true });
    writeFileSync(join(ROOT, path), want);
    console.log("wrote " + path);
  }
}
if (check) {
  if (stale.length) {
    console.error("out of date, run `node tools/gen.mjs`:\n  " + stale.join("\n  "));
    process.exit(1);
  }
  console.log(`generated files up to date (${Object.keys(outputs).length})`);
}
